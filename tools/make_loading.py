#!/usr/bin/env python3
"""make_loading.py - the loading picture for the loader (SBlocks).

  make_loading.py picture.jpg src/bin/loading.bin src/loading_gen.s preview.png

The picture is cropped to the screen of the monitor, scaled to 320 x 256 and
reduced to 32 colours of the Amiga's 4096 (no dithering: it is pixel art).
The progress bar is made empty, and a full version of it is kept apart, so
the loader can fill it while the game loads; the "68%" is taken out (the
loader writes the real number there).

loading.bin: 5 planes of 40 x 256 bytes, then 32 colours (words).
loading_gen.s: where the bar and the number are, the full and the empty bar
(planar strips) and the clean patch behind the number."""
import sys
import numpy as np
from PIL import Image
from scipy.cluster.vq import kmeans2

src, out_bin, out_s, out_png = sys.argv[1:5]
W, H = 320, 256
im = Image.open(src).convert('RGB')
sw, sh = im.size

# the line at the bottom left: what the game really needs
NEW_LINE = 'Kickstart 1.3 \u2022 512K CHIP RAM \u2022 WORKBENCH 1.3'
def fix_text(im):
    from PIL import ImageDraw, ImageFont
    a = np.asarray(im).astype(float)
    x0, x1, y0, y1 = 150, 885, 1168, 1226
    for y in range(y0, y1):
        row = a[y, x0:x1]
        bg = row[(row * (0.3, 0.59, 0.11)).sum(1) < 90]       # the blue, not the letters
        if len(bg) == 0: bg = row
        a[y, x0:x1] = np.median(bg, 0)
    im = Image.fromarray(a.astype(np.uint8))
    d = ImageDraw.Draw(im)
    size = 34
    while True:
        f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', size)
        if d.textlength(NEW_LINE, font=f) <= 700 or size < 16: break
        size -= 1
    d.text((166, 1197), NEW_LINE, font=f, fill=(205, 228, 255), anchor='lm')
    return im
if sw == 1920 and sh == 1280:
    im = fix_text(im)
# the screen of the monitor (the picture is 1920 x 1280)
box = (round(120 * sw / 1920), 0, round(1800 * sw / 1920), sh)
im = im.crop(box).resize((W, H), Image.LANCZOS)
a = np.asarray(im).astype(float)

# 32 colours: k-means, rounded to 4 bits a gun
px = a.reshape(-1, 3)
cent, _ = kmeans2(px, 32, minit='++', iter=50, seed=11)
pal = np.unique(np.clip(np.round(cent / 17), 0, 15).astype(int), axis=0)
while len(pal) < 32:
    pal = np.vstack([pal, [[0, 0, 0]]])
pal = pal[np.argsort(pal.sum(1))]           # darkest first: colour 0 = the border
P = pal * 17.0
d = ((a[:, :, None, :] - P[None, None, :, :]) ** 2 * (0.3, 0.59, 0.11)).sum(-1)
idx = d.argmin(-1)

def X(x): return round((x - 120) * 320 / 1680)
def Y(y): return round(y * 256 / 1280)

# ---- the bar: bytes BAR_B0 .. BAR_B1 (8 pixels each), rows BAR_Y0 .. BAR_Y1
BAR_Y0, BAR_Y1 = Y(785) - 1, Y(848) + 1
fill_end = X(1170)                          # where the cyan ends in the picture
BAR_B0, BAR_B1 = (X(372) + 7) // 8, (X(1545) - 1) // 8
x0, x1 = BAR_B0 * 8, BAR_B1 * 8 + 7
full = idx.copy()
empty = idx.copy()
seg = fill_end - 2 - x0                     # the filled part repeats over the whole bar
grey = (x1 - 6) - (fill_end + 3)
for x in range(x0, x1 + 1):
    full[BAR_Y0:BAR_Y1 + 1, x] = idx[BAR_Y0:BAR_Y1 + 1, x0 + (x - x0) % seg]
    empty[BAR_Y0:BAR_Y1 + 1, x] = idx[BAR_Y0:BAR_Y1 + 1, fill_end + 3 + (x - x0) % grey]
pic = empty.copy()                          # the picture starts with an empty bar

# ---- the number: "68%" away, the loader writes "NN%" (8x8 font) there
NUM_Y = Y(885) + 1
NUM_B = X(1085) // 8                        # its first byte
NUM_W = 4                                   # bytes: "100%"
ny0, ny1 = NUM_Y - 2, NUM_Y + 9
bgx = X(1085) - 6                           # the background just left of it
for y in range(ny0, ny1 + 1):
    pic[y, NUM_B * 8 - 2:(NUM_B + NUM_W) * 8 + 4] = pic[y, bgx]
# the colour of the text: the commonest light colour in "LOADING..."
region = idx[Y(885):Y(925), X(725):X(1050)]
lum = (P[region] * (0.3, 0.59, 0.11)).sum(-1)
vals, cnt = np.unique(region[lum > 120], return_counts=True)
TXT = int(vals[cnt.argmax()])

def planes_of(arr, x0b, nb, y0, y1):
    out = []
    for p in range(5):
        for y in range(y0, y1 + 1):
            for b in range(x0b, x0b + nb):
                v = 0
                for k in range(8):
                    if (arr[y, b * 8 + k] >> p) & 1: v |= 0x80 >> k
                out.append(v)
    return out

with open(out_bin, 'wb') as f:
    f.write(bytes(planes_of(pic, 0, 40, 0, H - 1)))
    for c in pal:
        f.write(bytes([c[0], (c[1] << 4) | c[2]]))

L = ['; generated by tools/make_loading.py - do not edit',
     f'BAR_Y0\tequ\t{BAR_Y0}', f'BAR_H\tequ\t{BAR_Y1 - BAR_Y0 + 1}',
     f'BAR_B0\tequ\t{BAR_B0}', f'BAR_NB\tequ\t{BAR_B1 - BAR_B0 + 1}',
     f'NUM_Y\tequ\t{NUM_Y}', f'NUM_B\tequ\t{NUM_B}', f'NUM_W\tequ\t{NUM_W}',
     f'NUM_PY\tequ\t{ny0}', f'NUM_PH\tequ\t{ny1 - ny0 + 1}', f'TXT_COL\tequ\t{TXT}']
def dcb(label, vals):
    L.append(f'{label}:')
    for i in range(0, len(vals), 32):
        L.append('\tdc.b\t' + ','.join(f'${v:02x}' for v in vals[i:i + 32]))
dcb('BarFull', planes_of(full, BAR_B0, BAR_B1 - BAR_B0 + 1, BAR_Y0, BAR_Y1))
dcb('BarEmpty', planes_of(empty, BAR_B0, BAR_B1 - BAR_B0 + 1, BAR_Y0, BAR_Y1))
dcb('NumPatch', planes_of(pic, NUM_B, NUM_W, ny0, ny1))
L.append('\teven')
open(out_s, 'w').write('\n'.join(L) + '\n')

prev = P[pic].astype(np.uint8)
Image.fromarray(P[full].astype(np.uint8)).crop((0, BAR_Y0 - 8, W, BAR_Y1 + 8)).resize((960, (BAR_Y1 - BAR_Y0 + 17) * 3), Image.NEAREST).save(out_png.replace('.png', '_full.png'))
Image.fromarray(prev).resize((960, 768), Image.NEAREST).save(out_png)
print('bar bytes', BAR_B0, BAR_B1, 'rows', BAR_Y0, BAR_Y1, 'number at byte', NUM_B, 'y', NUM_Y, 'text colour', TXT,
      'palette', ' '.join('%x%x%x' % tuple(c) for c in pal))
